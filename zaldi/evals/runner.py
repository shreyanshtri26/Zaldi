"""``python -m zaldi evals [retrieval|redteam|agent|all] [--write] [--live]``
(``all`` is the two offline suites; add ``--live`` or run ``agent`` to spend model quota)

The offline suites (retrieval, redteam) run on a throwaway copy of the seed catalogue with the local embedder, so the numbers
are the same on every machine and in CI. The agent suite uses your configured model and database and needs a key.
``--write`` saves ``evals/results/latest.json`` and ``evals/RESULTS.md``.
"""
import json
import sys
import tempfile
from pathlib import Path

from zaldi import config

ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = ROOT / "evals" / "results"


def offline_environment():
    """Point the app at a temporary seeded database with offline embeddings. Returns the previous settings to restore."""
    tmp = Path(tempfile.mkdtemp(prefix="zaldi-evals-"))
    saved = {k: getattr(config, k) for k in ("DB_PATH", "PRODUCT_INDEX_DIR", "POLICY_INDEX_DIR", "EMBEDDING_PROVIDER", "DATABASE_URL")}
    config.DATABASE_URL = ""  # the offline suites always run on a throwaway SQLite copy
    config.DB_PATH, config.PRODUCT_INDEX_DIR, config.POLICY_INDEX_DIR = tmp / "eval.db", tmp / "product_index", tmp / "policy_index"
    config.EMBEDDING_PROVIDER = "local"
    from zaldi.db import init_db

    init_db()
    return saved


def restore(saved: dict) -> None:
    for key, value in saved.items():
        setattr(config, key, value)


def run_retrieval() -> dict:
    from zaldi.evals import retrieval

    return retrieval.evaluate()


def run_redteam() -> dict:
    from zaldi.evals import redteam

    return {"input": redteam.input_attacks(), "indirect": redteam.indirect_attacks(), "tools": redteam.tool_attacks()}


def run_agent_suite() -> dict:
    from zaldi.ai.models import get_llm
    from zaldi.connectors import get_connector
    from zaldi.evals import agent_eval

    return agent_eval.run_all(get_connector(), get_llm())


def markdown(results: dict) -> str:
    out = ["# Evaluation results", "", "Generated by `python -m zaldi evals all --write`. Retrieval and red-team numbers are reproducible offline.", ""]
    if "retrieval" in results:
        r = results["retrieval"]
        out += [f"## Product search ({r['queries']} generated queries, top {r['k']})", "",
                "| Method | Hit rate | MRR | nDCG | Recall |", "|---|---|---|---|---|"]
        for name, m in r["methods"].items():
            o = m["overall"]
            out.append(f"| {name} | {o['hit']:.3f} | {o['mrr']:.3f} | {o['ndcg']:.3f} | {o['recall']:.3f} |")
        out += ["", "Labels are rule-made from the catalogue's own attributes, so they test ranking consistency, not shopper taste.", ""]
    if "redteam" in results:
        x = results["redteam"]
        i, d, t = x["input"], x["indirect"], x["tools"]
        out += ["## Attack resistance", "", "| Layer | Result |", "|---|---|",
                f"| Hostile messages refused | {i['blocked']} / {i['total']} |",
                f"| Ordinary shopping wrongly refused | {len(i['false_positives'])} / {i['benign_total']} |",
                f"| Instructions hidden in store text neutralised | {d['neutralized']} / {d['total']} |",
                f"| Normal store text left intact | {d['safe_total'] - len(d['safe_damaged'])} / {d['safe_total']} |",
                f"| Tool-layer attacks stopped by code | {t['stopped']} / {t['total']} |", "",
                "The attack lists were written together with the rules, so this is a regression gate, not a claim of general robustness.", ""]
    if "agent" in results:
        s = results["agent"]["summary"]
        out += [f"## Agent with a live model ({s['cases']} cases)", "", "| Metric | Value |", "|---|---|",
                f"| Tool-choice accuracy | {s['tool_choice_accuracy']:.1%} |", f"| Faithfulness (no unsupported amounts) | {s['faithfulness']:.1%} |",
                f"| Latency p50 / p95 | {s['latency_ms_p50']} ms / {s['latency_ms_p95']} ms |", f"| Cost per chat (estimated) | ${s['cost_usd_per_chat']:.4f} |",
                f"| Tokens per chat | {s['tokens_per_chat']} |", f"| Model errors | {s['model_errors']} |", ""]
    return "\n".join(out)


def check_thresholds(results: dict) -> list[str]:
    """Names of every threshold in ``evals/thresholds.json`` that the results fall below (empty list = all clear)."""
    limits = json.loads((ROOT / "evals" / "thresholds.json").read_text(encoding="utf-8"))
    failed = []
    for method, mins in limits["retrieval"].items():
        for metric, floor in mins.items():
            got = results["retrieval"]["methods"][method]["overall"][metric]
            if got < floor:
                failed.append(f"retrieval {method} {metric} {got} < {floor}")
    r, lim = results["redteam"], limits["redteam"]
    checks = [("input block rate", r["input"]["blocked"] / r["input"]["total"], lim["input_block_rate"], ">="),
              ("benign false positives", len(r["input"]["false_positives"]), lim["benign_false_positives"], "<="),
              ("indirect neutralised rate", r["indirect"]["neutralized"] / r["indirect"]["total"], lim["indirect_neutralized_rate"], ">="),
              ("safe text damaged", len(r["indirect"]["safe_damaged"]), lim["indirect_safe_damaged"], "<="),
              ("tool stop rate", r["tools"]["stopped"] / r["tools"]["total"], lim["tool_stop_rate"], ">=")]
    for name, got, bound, op in checks:
        if (op == ">=" and got < bound) or (op == "<=" and got > bound):
            failed.append(f"redteam {name}: {got} (needs {op} {bound})")
    return failed


def main(argv: list[str]) -> int:
    which = next((a for a in argv if not a.startswith("--")), "all")
    if which == "harvest":
        from zaldi.db import init_db
        from zaldi.evals.harvest import harvest

        init_db()
        print(f"Added {harvest()} new cases to evals/harvested.jsonl")
        return 0
    write = "--write" in argv
    results: dict = {}
    saved = offline_environment() if which in ("retrieval", "redteam", "all") else None
    try:
        if which in ("retrieval", "all"):
            results["retrieval"] = run_retrieval()
        if which in ("redteam", "all"):
            results["redteam"] = run_redteam()
    finally:
        if saved:
            restore(saved)
    if which == "agent" or "--live" in argv:  # spends model quota, so never part of a plain "all"
        try:
            from zaldi.db import init_db

            init_db()
            agent = run_agent_suite()
            if agent["summary"]["model_errors"] > agent["summary"]["cases"] // 4:  # numbers from a model that was down would mislead
                print(f"agent suite not reported: the model failed on {agent['summary']['model_errors']} of {agent['summary']['cases']} cases (rate limit or outage). Run it again later.")
            else:
                results["agent"] = agent
        except Exception as exc:
            print(f"agent suite skipped: {type(exc).__name__}: {str(exc)[:160]}")
    print(markdown(results))
    failed = check_thresholds(results) if {"retrieval", "redteam"} <= set(results) else []
    for f in failed:
        print("FAILED:", f)
    if write:
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        slim = {k: v for k, v in results.items()}
        (RESULTS_DIR / "latest.json").write_text(json.dumps(slim, indent=2, default=lambda o: sorted(o) if isinstance(o, set) else str(o)), encoding="utf-8")
        (ROOT / "evals" / "RESULTS.md").write_text(markdown(results), encoding="utf-8")
        print("wrote evals/RESULTS.md and evals/results/latest.json")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
